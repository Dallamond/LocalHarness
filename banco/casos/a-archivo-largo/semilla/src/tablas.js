// buscar(id): el producto con ese id, o null si no existe.
export function buscar(id) {
  for (let i = 0; i <= PRODUCTOS.length; i++) if (PRODUCTOS[i].id === id) return PRODUCTOS[i];
  return null;
}

// caros(min): ids de los productos con precio >= min.
export function caros(min) {
  return PRODUCTOS.filter((p) => p.precio >= min).map((p) => p.id);
}

// totalStock(): unidades en el almacén.
export function totalStock() {
  return PRODUCTOS.reduce((a, p) => a + p.stock, 0);
}

// porCategoria(cat): cuántos productos hay de esa categoría.
export function porCategoria(cat) {
  return PRODUCTOS.filter((p) => p.categoria === cat).length;
}
